-- 1) El rol médico puede LEER la fecha de control (sólo SELECT; no escribe: la RPC de control sigue siendo de owner/admin).
-- 2) La RPC de confirmación rechaza (PR412) toda prestación sin arancel válido FIJADO en la atención; el importe presentado debe ser el fijado (el cliente no lo define). arancel_id se toma de la atención.
-- No toca datos, tablas, atenciones ni otras políticas. Una transacción; falla (y revierte) si el bloque no está aplicado. Rollback: ..._delta_incidencias_rollback.sql
BEGIN;
DO $$
BEGIN
  IF to_regprocedure('public.cardiolink_presentacion_os_confirmar_v1(text,jsonb)') IS NULL OR to_regclass('public.cardiolink_presentaciones_os_control_v1') IS NULL THEN
    RAISE EXCEPTION 'Precondición: el bloque Presentaciones OS V1 no está aplicado'; END IF;
  IF (SELECT count(*) FROM pg_policies WHERE schemaname = 'public' AND policyname = 'cardiolink_presentaciones_os_control_select') <> 1 THEN
    RAISE EXCEPTION 'Precondición: falta la política cardiolink_presentaciones_os_control_select'; END IF;
